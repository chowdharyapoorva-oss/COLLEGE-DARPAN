def seed_database():
    """Populates the database with multi-category Telangana college records, metrics, branches, and cutoffs."""
    conn = get_db_connection()
    cursor = conn.cursor()

    try:
        # Check if already seeded to prevent duplicate records
        cursor.execute("SELECT COUNT(*) as count FROM colleges")
        row = cursor.fetchone()
        if row and row["count"] > 0:
            print(f"[Seed] Database already contains {row['count']} colleges. Skipping seed.")
            return

        print("[Seed] Seeding multi-category Telangana institution dataset (Polytechnic, Engineering, Pharmacy)...")
        
        for c in COLLEGES_DATA:
            cursor.execute("""
                INSERT INTO colleges (name, college_code, district, city, address, primary_category, 
                                     institution_type, management_type, official_website, contact_email, 
                                     contact_phone, description, est_year, campus_area_acres, 
                                     naac_grade, nirf_band, approval_body, hostel_available, 
                                     transport_available, verification_status, source_url, last_checked_date)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, (
                c["name"], c["college_code"], c["district"], c.get("city", c["district"]), c["address"],
                c.get("primary_category", "engineering"), c["institution_type"], c.get("management_type", "Private"),
                c.get("official_website"), c.get("contact_email"), c.get("contact_phone"),
                c["description"], c.get("est_year"), c.get("campus_area_acres"),
                c.get("naac_grade"), c.get("nirf_band"), c.get("approval_body", "AICTE"),
                c.get("hostel_available", 0), c.get("transport_available", 1),
                c.get("verification_status", "Verified"), c.get("source_url"), c.get("last_checked_date", "2024-09-01")
            ))
            college_id = cursor.lastrowid

            # Insert Metrics
            m = c.get("metrics")
            if m:
                cursor.execute("""
                    INSERT INTO college_metrics (college_id, academic_year, annual_tuition_fee, 
                                                other_fees, govt_concession_fee, placement_percentage, 
                                                average_package, highest_package, median_package, 
                                                eligible_students_count, placed_students_count,
                                                top_recruiters, faculty_information, infrastructure_information, 
                                                laboratories_information, hostel_information, internship_support, 
                                                source_url, last_updated, verification_status, notes)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """, (
                    college_id, m["academic_year"], m.get("annual_tuition_fee"), m.get("other_fees"),
                    m.get("govt_concession_fee", 0.0), m.get("placement_percentage"), m.get("average_package"),
                    m.get("highest_package"), m.get("median_package"), m.get("eligible_students_count"),
                    m.get("placed_students_count"), m.get("top_recruiters"), m.get("faculty_information"),
                    m.get("infrastructure_information"), m.get("laboratories_information"),
                    m.get("hostel_information"), m.get("internship_support"), m.get("source_url"),
                    m.get("last_updated"), m.get("verification_status", "Verified"), m.get("notes")
                ))

            # Insert Branches / Programmes and track their IDs
            branch_id_map = {}
            for b in c.get("branches", []):
                cursor.execute("""
                    INSERT INTO branches (college_id, category, degree_level, course_name, 
                                         branch_name, branch_code, duration_years, seats_intake, 
                                         program_status, admission_route, eligibility_criteria, 
                                         approval_info, source, academic_year, verification_status)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """, (
                    college_id, b.get("category", c.get("primary_category", "engineering")),
                    b.get("degree", "B.Tech"), b.get("course", b["name"]), b["name"], b["code"],
                    b.get("duration", 4), b.get("seats", 60), "Active",
                    b.get("route", "TS EAPCET"), b.get("eligibility", "10+2 or Diploma"),
                    b.get("approval_info", "AICTE Approved"), "Official Institutional Disclosure",
                    "2024-25", "Verified"
                ))
                branch_id_map[b["code"]] = cursor.lastrowid

            # Insert Cutoffs
            for cut in c.get("cutoffs", []):
                b_code = cut["branch"]
                b_id = branch_id_map.get(b_code)
                if b_id:
                    cursor.execute("""
                        INSERT INTO admission_cutoffs (college_id, branch_id, exam_name, 
                                                      admission_year, admission_pathway, category, 
                                                      cutoff_rank, source_url, verification_status)
                        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """, (
                        college_id, b_id, cut["exam"], cut["year"], cut["pathway"],
                        cut["category"], cut["rank"], "Official Counselling Authority Records", "Verified"
                    ))

        conn.commit()
        print(f"[Seed] Successfully seeded {len(COLLEGES_DATA)} institutions across Polytechnic, B.Tech, and Pharmacy.")
    except Exception as e:
        conn.rollback()
        print(f"[Seed Error] {e}")
        raise e
    finally:
        conn.close()

if __name__ == "__main__":
    seed_database()
